/// Whether `c` lies in one of the sorted, disjoint `ranges`.
pub(super) fn contains(ranges: &[(u32, u32)], c: char) -> bool {
    let c = u32::from(c);
    ranges
        .binary_search_by(|&(lo, hi)| {
            if hi < c {
                std::cmp::Ordering::Less
            } else if lo > c {
                std::cmp::Ordering::Greater
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}
